{
    Left,
    Right,
    Up,
    Down,
    PageUp,
    PageDown,
    LineStart,
    LineEnd,
    TextStart,
    TextEnd,
    WordLeft,
    WordRight,
    Delete,
    Backspace,
    Undo,
    Redo,
    Insert,
}
